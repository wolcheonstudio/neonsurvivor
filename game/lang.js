let savedLang = 'en';
try {
  const urlParams = new URLSearchParams(window.location.search);
  const urlLang = urlParams.get('lang');
  if (urlLang && (urlLang === 'en' || urlLang === 'ko')) {
    savedLang = urlLang;
    try { localStorage.setItem('ns_lang', savedLang); } catch(e){}
  } else {
    const localLang = localStorage.getItem('ns_lang');
    if (localLang && (localLang === 'en' || localLang === 'ko')) {
      savedLang = localLang;
    } else {
      const browserLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
      savedLang = browserLang.startsWith('ko') ? 'ko' : 'en';
    }
  }
} catch (e) {
  const browserLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
  savedLang = browserLang.startsWith('ko') ? 'ko' : 'en';
}
window.currentLang = savedLang;

function setLanguage(lang) {
  window.currentLang = lang;
  try {
    localStorage.setItem('ns_lang', lang);
  } catch (e) {
    console.warn("Storage write failed (sandboxed or local file origin).");
  }
  updateTexts();
  
  // Re-render shop and upgrades if they are exposed
  if (typeof window.renderShop === 'function') window.renderShop();
  if (typeof window.renderWeaponShop === 'function') window.renderWeaponShop();
  
  // Update toggle UI
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.remove('active');
    if (btn.id.endsWith('_' + lang)) btn.classList.add('active');
  });
}

function updateTexts() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (I18N[window.currentLang][key]) {
      el.innerHTML = I18N[window.currentLang][key];
    }
  });
}

function t(key, ...args) {
  let str = I18N[window.currentLang][key] || key;
  for (let i = 0; i < args.length; i++) {
    str = str.replace(`{${i}}`, args[i]);
  }
  return str;
}

document.addEventListener('DOMContentLoaded', () => {
  updateTexts();
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.remove('active');
    if (btn.id.endsWith('_' + window.currentLang)) btn.classList.add('active');
  });
});
